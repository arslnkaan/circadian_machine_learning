# 35. HELPER TO MERGE PREDICTORS INTO MODELING DATASET
# ============================================================

merge_predictors <- function(
    phenotype_file,
    keep_columns,
    output_name
) {
  
  x <- fread(
    phenotype_file
  )
  
  
  missing_cols <- setdiff(
    keep_columns,
    names(x)
  )
  
  
  if (
    length(missing_cols) > 0
  ) {
    
    stop(
      
      "Missing columns in:\n",
      phenotype_file,
      "\n\n",
      
      paste(
        missing_cols,
        collapse = ", "
      )
      
    )
    
  }
  
  
  x <- x[
    ,
    ..keep_columns
  ]
  
  
  out <- merge(
    
    x,
    
    predictors,
    
    by =
      "gene",
    
    all.x =
      TRUE,
    
    sort =
      FALSE
    
  )
  
  
  out[
    ,
    genomic_predictors_available :=
      !is.na(
        gene_length_bp
      )
  ]
  
  
  fwrite(
    
    out,
    
    file.path(
      OUTDIR,
      output_name
    ),
    
    sep = "\t"
    
  )
  
  
  out
  
}


