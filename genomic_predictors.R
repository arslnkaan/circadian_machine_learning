# 7. HARMONIZE CHROMOSOME NAMES TO FASTA
# ============================================================

harmonize_seqname <- function(
    x,
    reference_names
) {
  
  candidates <- x
  
  
  if (
    startsWith(
      x,
      "chr"
    )
  ) {
    
    candidates <- c(
      candidates,
      sub(
        "^chr",
        "",
        x
      )
    )
    
  } else {
    
    candidates <- c(
      candidates,
      paste0(
        "chr",
        x
      )
    )
    
  }
  
  
  if (
    x %in%
    c(
      "M",
      "MT",
      "chrM",
      "chrMT"
    )
  ) {
    
    candidates <- c(
      
      candidates,
      
      "M",
      "MT",
      "chrM",
      "chrMT"
      
    )
    
  }
  
  
  candidates <- unique(
    candidates
  )
  
  
  hit <- candidates[
    candidates %in%
      reference_names
  ]
  
  
  if (
    length(hit) == 0
  ) {
    
    return(
      NA_character_
    )
    
  }
  
  
  hit[1]
  
}


