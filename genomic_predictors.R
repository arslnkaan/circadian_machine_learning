# 21. PROMOTER WINDOW HELPER
#
# rel_start / rel_end are coordinates relative to TSS
# in TRANSCRIPTION DIRECTION.
# ============================================================

make_relative_window <- function(
    genes,
    rel_start,
    rel_end,
    label
) {
  
  if (
    rel_start >
    rel_end
  ) {
    
    stop(
      "rel_start must be <= rel_end."
    )
    
  }
  
  
  x <- genes[
    ,
    .(
      gene,
      chromosome,
      strand,
      tss
    )
  ]
  
  
  x[
    strand == "+",
    untrimmed_start :=
      tss +
      rel_start
  ]
  
  
  x[
    strand == "+",
    untrimmed_end :=
      tss +
      rel_end
  ]
  
  
  x[
    strand == "-",
    untrimmed_start :=
      tss -
      rel_end
  ]
  
  
  x[
    strand == "-",
    untrimmed_end :=
      tss -
      rel_start
  ]
  
  
  x[
    ,
    chromosome_length :=
      as.integer(
        fasta_lengths[
          chromosome
        ]
      )
  ]
  
  
  if (
    anyNA(
      x$chromosome_length
    )
  ) {
    
    stop(
      "Some gene chromosomes were not found in FASTA."
    )
    
  }
  
  
  x[
    ,
    genomic_start :=
      pmax(
        1L,
        untrimmed_start
      )
  ]
  
  
  x[
    ,
    genomic_end :=
      pmin(
        chromosome_length,
        untrimmed_end
      )
  ]
  
  
  if (
    any(
      x$genomic_start >
      x$genomic_end
    )
  ) {
    
    stop(
      "Invalid promoter interval after chromosome clipping."
    )
    
  }
  
  
  x[
    ,
    clipped :=
      genomic_start !=
      untrimmed_start |
      genomic_end !=
      untrimmed_end
  ]
  
  
  x[
    ,
    expected_width :=
      rel_end -
      rel_start +
      1L
  ]
  
  
  x[
    ,
    actual_width :=
      genomic_end -
      genomic_start +
      1L
  ]
  
  
  gr <- GenomicRanges::GRanges(
    
    seqnames =
      x$chromosome,
    
    ranges =
      IRanges::IRanges(
        
        start =
          x$genomic_start,
        
        end =
          x$genomic_end
        
      ),
    
    strand =
      "*"
    
  )
  
  
  names(gr) <-
    x$gene
  
  
  list(
    
    label =
      label,
    
    info =
      x,
    
    gr =
      gr
    
  )
  
}


