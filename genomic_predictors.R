get_gtf_attribute <- function(
    gr,
    candidates,
    required = FALSE
) {
  
  available <- names(
    mcols(gr)
  )
  
  
  hit <- candidates[
    candidates %in%
      available
  ]
  
  
  if (
    length(hit) == 0
  ) {
    
    if (required) {
      
      stop(
        
        "Could not find required GTF attribute.\n",
        
        "Tried:\n",
        
        paste(
          candidates,
          collapse = ", "
        ),
        
        "\n\nAvailable attributes:\n",
        
        paste(
          available,
          collapse = ", "
        )
        
      )
      
    }
    
    
    return(
      rep(
        NA_character_,
        length(gr)
      )
    )
    
  }
  
  
  as.character(mcols(gr)[[hit[1]]])
  
}


