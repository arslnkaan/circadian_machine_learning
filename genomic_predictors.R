# 24. EXTRACT ORIENTED PROMOTER SEQUENCES
# ============================================================

extract_oriented_sequence <- function(
    window_object
) {
  
  seqs <- Rsamtools::scanFa(
    
    fa,
    
    param =
      window_object$gr
    
  )
  
  
  names(seqs) <-
    window_object$info$gene
  
  
  minus <- window_object$info$strand ==
    "-"
  
  
  if (
    any(minus)
  ) {
    
    seqs[
      minus
    ] <- Biostrings::reverseComplement(
      
      seqs[
        minus
      ]
      
    )
    
  }
  
  
  seqs
  
}


