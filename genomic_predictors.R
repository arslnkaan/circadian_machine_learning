# ============================================================
# 27. COUNT MOTIF ON BOTH DNA ORIENTATIONS
# ============================================================

count_motif_both_strands <- function(
    seqs,
    pattern
) {
  
  rc <- as.character(
    
    Biostrings::reverseComplement(
      
      Biostrings::DNAString(
        pattern
      )
      
    )
    
  )
  
  
  forward_count <- Biostrings::vcountPattern(
    
    pattern =
      pattern,
    
    subject =
      seqs,
    
    fixed =
      "subject"
    
  )
  
  
  # Avoid double counting palindromic/self-RC motifs.
  if (
    identical(
      pattern,
      rc
    )
  ) {
    
    return(
      as.integer(
        forward_count
      )
    )
    
  }
  
  
  reverse_count <- Biostrings::vcountPattern(
    
    pattern =
      rc,
    
    subject =
      seqs,
    
    fixed =
      "subject"
    
  )
  
  
  as.integer(
    forward_count +
      reverse_count
  )
  
}


# ============================================================
# 28. CALCULATE SEQUENCE FEATURES
# ============================================================

calculate_sequence_features <- function(
    seqs,
    prefix
) {
  
  nucleotide_counts <- Biostrings::letterFrequency(
    
    seqs,
    
    letters = c(
      "A",
      "C",
      "G",
      "T"
    ),
    
    as.prob =
      FALSE
    
  )
  
  
  valid_bp <- rowSums(
    nucleotide_counts
  )
  
  
  total_bp <- width(
    seqs
  )
  
  
  cpg_count <- as.integer(
    
    Biostrings::vcountPattern(
      
      "CG",
      
      seqs,
      
      fixed = TRUE
      
    )
    
  )
  
  
  result <- data.table(
    
    gene =
      names(seqs),
    
    sequence_width_bp =
      as.integer(
        total_bp
      ),
    
    valid_ACGT_bp =
      as.integer(
        valid_bp
      ),
    
    ambiguous_bp =
      as.integer(
        total_bp -
          valid_bp
      ),
    
    A_count =
      nucleotide_counts[
        ,
        "A"
      ],
    
    C_count =
      nucleotide_counts[
        ,
        "C"
      ],
    
    G_count =
      nucleotide_counts[
        ,
        "G"
      ],
    
    T_count =
      nucleotide_counts[
        ,
        "T"
      ],
    
    GC_percent =
      fifelse(
        
        valid_bp > 0,
        
        100 *
          (
            nucleotide_counts[
              ,
              "G"
            ] +
              nucleotide_counts[
                ,
                "C"
              ]
          ) /
          valid_bp,
        
        NA_real_
        
      ),
    
    CpG_count =
      cpg_count,
    
    CpG_per_kb =
      fifelse(
        
        valid_bp > 0,
        
        cpg_count /
          (
            valid_bp /
              1000
          ),
        
        NA_real_
        
      ),
    
    CpG_observed_expected =
      fifelse(
        
        nucleotide_counts[
          ,
          "C"
        ] > 0 &
          
          nucleotide_counts[
            ,
            "G"
          ] > 0,
        
        cpg_count *
          valid_bp /
          (
            nucleotide_counts[
              ,
              "C"
            ] *
              nucleotide_counts[
                ,
                "G"
              ]
          ),
        
        NA_real_
        
      )
    
  )
  
  
  # ----------------------------------------------------------
  # Motif features
  # ----------------------------------------------------------
  
  for (
    i in seq_len(
      nrow(motifs)
    )
  ) {
    
    motif_name <-
      motifs$feature_name[i]
    
    
    motif_pattern <-
      motifs$pattern[i]
    
    
    motif_count <- count_motif_both_strands(
      
      seqs =
        seqs,
      
      pattern =
        motif_pattern
      
    )
    
    
    result[
      ,
      (paste0(
        motif_name,
        "_count"
      )) :=
        motif_count
    ]
    
    
    result[
      ,
      (paste0(
        motif_name,
        "_per_kb"
      )) :=
        fifelse(
          
          valid_bp > 0,
          
          motif_count /
            (
              valid_bp /
                1000
            ),
          
          NA_real_
          
        )
    ]
    
  }
  
  
  # ----------------------------------------------------------
  # Canonical E-box fraction
  #
  # Among all CANNTG sites, what fraction are CACGTG?
  # ----------------------------------------------------------
  
  result[
    ,
    ebox_canonical_fraction :=
      fifelse(
        
        ebox_CANNTG_count >
          0,
        
        ebox_CACGTG_count /
          ebox_CANNTG_count,
        
        0
        
      )
  ]
  
  
  # ----------------------------------------------------------
  # Prefix all feature names except gene.
  # ----------------------------------------------------------
  
  feature_columns <- setdiff(
    names(result),
    "gene"
  )
  
  
  setnames(
    
    result,
    
    feature_columns,
    
    paste0(
      prefix,
      "_",
      feature_columns
    )
    
  )
  
  
  result
  
}


