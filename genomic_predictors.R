# ============================================================
# XR-seq DEVELOPMENTAL RHYTHMICITY
#
# GENERATE GENE-INTRINSIC GENOMIC PREDICTORS
#
# mm10 / GRCm38
#
# ============================================================
#
# Generates:
#
#   gene architecture
#   promoter GC content
#   promoter CpG count/density/O:E
#
# Circadian promoter motifs:
#
#   E-box canonical     CACGTG
#   E-box broad         CANNTG
#   E'-box              CACGTT (+ reverse complement)
#   D-box               TTATGYAA
#   RRE                 WAWNTRGGTCA
#   RORE core           RGGTCA
#
# Windows:
#
#   full promoter       -2000 : +500
#   proximal promoter    -500 : +100
#   distal promoter     -2000 : -501
#
# Coordinates are defined RELATIVE TO TRANSCRIPTION DIRECTION.
#
# ============================================================


